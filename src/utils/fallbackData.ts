/**
 * Perform offline local fallback translation for dynamic objects
 */
export function getFallbackTranslation(fields: Record<string, string>, targetLang: string): Record<string, string> {
  const result: Record<string, string> = { ...fields };
  const translationsMap = FALLBACK_TRANSLATIONS[targetLang];

  if (!translationsMap) {
    return result;
  }

  // Determine if this corresponds to a known mock item by checking fields.title
  let mockItemId: string | undefined = undefined;
  if (fields.title && typeof fields.title === "string") {
    mockItemId = titleToIdMap[fields.title];
  }

  const mockItemTranslations = mockItemId ? FALLBACK_ITEMS_DB[mockItemId]?.[targetLang] : undefined;

  // Iterate over each field to translate
  for (const [key, value] of Object.entries(fields)) {
    if (typeof value !== "string") continue;

    const trimmedValue = value.trim();

    // 1. If it's a mock item, use the dedicated translation for that field if available
    if (mockItemTranslations) {
      if (key === "title" && mockItemTranslations.title) {
        result[key] = mockItemTranslations.title;
        continue;
      }
      if (key === "description" && mockItemTranslations.description) {
        result[key] = mockItemTranslations.description;
        continue;
      }
      if (key === "longDescription" && mockItemTranslations.longDescription) {
        result[key] = mockItemTranslations.longDescription;
        continue;
      }
      if (key === "location" && mockItemTranslations.location) {
        result[key] = mockItemTranslations.location;
        continue;
      }
    }

    // 2. Check if the value is an exact match for one of the categories or locations
    if (translationsMap[trimmedValue]) {
      result[key] = translationsMap[trimmedValue];
      continue;
    }

    // 3. Fallback translation for generic strings/paragraphs (e.g. user stories)
    // We will do a basic keyword-level replacement of countries, categories, and common words,
    // and append a small localized tag or translate key words to make it look translated
    let translatedText = trimmedValue;

    // Replace common vocabulary and locations inside paragraphs
    for (const [englishWord, translation] of Object.entries(translationsMap)) {
      // Avoid replacing small sub-words by using word boundaries
      const regex = new RegExp(`\\b${englishWord}\\b`, "g");
      translatedText = translatedText.replace(regex, translation);
    }

    result[key] = translatedText;
  }

  return result;
}
